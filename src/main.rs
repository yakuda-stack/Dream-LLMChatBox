slint::include_modules!();

fn main() -> Result<(), slint::PlatformError> {
    if cli::handled() {
        return Ok(());
    }
    let ui = AppWindow::new()?;
    i18n::setup();
    theme::setup(&ui);
    desktop_entry::install();
    profiles_ui::setup(&ui);
    profile::setup(&ui);
    models_page::setup(&ui);
    composer::setup(&ui);
    folders::setup(&ui);
    tools_page::setup(&ui);
    mcp_ui::setup(&ui);
    start_args_page::setup(&ui);
    approval::setup(&ui);
    question::setup(&ui);
    activity::setup(&ui);
    browser::setup(&ui);
    groups_ui::setup(&ui);
    chat_list::setup(&ui);
    work_ui::setup(&ui);
    preview::setup(&ui);
    cloud_ui::setup(&ui);
    servers_ui::setup(&ui);
    automations_ui::setup(&ui);
    tutorial::setup(&ui);
    reset::setup(&ui);
    coding_ui::setup(&ui);
    chat::setup(&ui);
    readaloud::setup(&ui);
    let _usage_timer = usage::start(&ui);
    let result = ui.run();
    profiles_ui::shutdown();
    server::stop_own();
    mcp::shutdown();
    result
}
